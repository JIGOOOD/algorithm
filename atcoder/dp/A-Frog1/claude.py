INF = float('inf')

n = int(input())

# 1-indexed로 맞추기 위해 앞에 더미 0을 붙임.
# w[1] ~ w[n]이 1번 ~ n번 돌의 높이가 됨.
w = [0] + list(map(int, input().split()))

# dp[i] = i번 돌까지 도달하는 데 드는 최소 비용
# INF로 초기화하는 이유:
#   - dp[0]은 존재하지 않는 돌 → "도달 불가능"을 뜻해야 함
#   - 0으로 두면 i=2에서 dp[0] + |w[2]-w[0]| 가 후보로 끼어들어
#     가짜 경로를 만들어냄. min DP에서 불가능은 반드시 INF.
dp = [INF] * (n + 1)

# 기저조건: 출발점인 1번 돌은 이미 서 있으므로 비용 0
dp[1] = 0

# i=2부터 점화식이 유효 (dp[i-1], dp[i-2] 중 최소 하나는 확정된 상태)
for i in range(2, n + 1):
    # 마지막 선택은 둘 중 하나:
    #   (a) i-1번 돌에서 한 칸 점프
    #   (b) i-2번 돌에서 두 칸 점프
    # 각 경우의 "이전까지 비용 + 이번 점프 비용"을 비교해 작은 쪽 채택.
    # i=2일 때 (b)는 dp[0]=INF라 자동 탈락 → 별도 예외 처리 불필요.
    dp[i] = min(
        dp[i - 1] + abs(w[i] - w[i - 1]),   # (a)
        dp[i - 2] + abs(w[i] - w[i - 2])    # (b)
    )

print(dp[n])